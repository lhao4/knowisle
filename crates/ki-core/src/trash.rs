//! 回收站的领域类型。
//!
//! # 为什么这两个结构体在 `ki-core` 而不是 `ki-vault`
//!
//! 它们跨 IPC 出去，前端要拿它们渲染列表与提示。放 `ki-vault` 的话，
//! `ki-ipc` 得为它们写一份镜像 DTO——那正是 `tauri-specta` 要消灭的东西
//! （同 [`crate::node::FileNode`] 的理由）。它们没有 IO，也就没有违反 A2。
//!
//! # 三个字段都在回答「用户此刻要知道什么」
//!
//! - `name`：恢复时唯一能定位那条记录的键（磁盘上的真名，不是猜的）。
//! - `origin`：**这一刀存在的理由**。`a/b/c.md` 删掉之后，只靠文件名里的
//!   `c.md` 是回不去的；`None` 表示清单缺失/损坏，此时 UI 必须说清
//!   「原路径未知」，而不是默默显示一个根目录路径。
//! - `deleted_at`：列表按它倒序，用户找的是「我刚才删的那个」。
//!
//! 三者都**不参与**内容判定：文件还在不在，只由回收目录里有没有这条记录决定。

use serde::{Deserialize, Serialize};
use specta::Type;

/// 回收目录里的一条。
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct TrashEntry {
    /// 回收目录里的文件名（`<unix_ms>-<原名>`）。恢复时用它定位。
    ///
    /// 它是**磁盘上的真名**，不是 `origin` 的末段：两者在正常情况下一致，
    /// 但清单缺失时只剩它，而恢复必须能靠它把文件搬回去。
    pub entry: String,
    /// 展示用的原名（`c.md`）。
    ///
    /// 由 Rust 算：有原路径就取它的末段，没有就从 `entry` 里剥掉时间戳前缀。
    /// **不让前端各写一遍**——`<unix_ms>-` 的剥法一旦两边不一致，用户会看到
    /// 一个"名字和恢复出来的不一样"的列表，而且没有任何报错。
    pub name: String,
    /// 删除前它在 Vault 里的相对路径（POSIX）。
    ///
    /// `None` = 清单里没有这条记录，或者记录损坏/不可信。**不是错误**：
    /// 文件还在，只是不知道它原来在哪。前端必须把它显示成「原路径未知」，
    /// 恢复时落到库根目录并明确告知。
    pub origin: Option<String>,
    /// 删除时间（Unix 毫秒）。
    ///
    /// 三级来源：清单 → 文件名前缀 → 文件 mtime。所以它**恒有值**，
    /// 前端不需要为 `null` 写一条分支。
    pub deleted_at: i64,
    /// 字节数（磁盘真值）。
    pub size: u64,
}

/// 一次恢复的结果。
///
/// # 为什么不用 `Option<String>` 提示语
///
/// 「撞名改了名」与「原路径丢了落到根目录」是两件**可以同时发生**的事，
/// 而且前端对它们的措辞不同（一个说"已改名为"，一个说"原路径记录缺失"）。
/// 在 Rust 里拼一句话返回，等于把文案的所有权挪到领域层；返回事实、
/// 让 UI 决定怎么说，才是这一层该做的事。
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct RestoreResult {
    /// 恢复后它在 Vault 里的相对路径（POSIX）。
    pub path: String,
    /// 本来要落的路径。与 `path` 不同就说明撞名改了名。
    ///
    /// 清单缺失时它是「库根目录 + 从文件名里剥出来的原名」——即**降级后的
    /// 意图**，而不是一个假装知道的原路径。
    pub requested: String,
    /// 因为目标已存在而改了名（`c.md` → `c 2.md`）。两条都在，谁也没被覆盖。
    pub renamed: bool,
    /// 原路径不可知或不可用，落到了库根目录。
    ///
    /// 两种成因：清单里没有这条记录（损坏 / 崩溃在写清单之前），
    /// 或者原目录已经不存在了。前端对这两种说同一句话就够了——
    /// 用户要的是"它去哪了"，不是内部原因的区分。
    pub degraded: bool,
}
