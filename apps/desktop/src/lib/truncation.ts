/**
 * 截断横幅的**纯逻辑**。
 *
 * # 为什么不是 `App.tsx` 里的一行字符串
 *
 * 这段文案已经错过一次：上限数的是 **20000 个条目**（目录也算），横幅说的是
 * 「20000 个文件」，而且数字本身还是写死的——`ScanOptions` 的默认值改了，
 * 横幅会继续撒谎。抽成纯函数之后，两条约束才可以被断言：
 *
 * 1. **数字只来自 `ScanResult.limitEntries`**，函数里没有任何字面量；
 * 2. **「条目」与「篇」的区别必须出现**：目录也占额度，所以撞上限时能看到的
 *    笔记数恒不超过上限（ADR-015 门禁①：19900 / 19049，不是 20000）。
 *
 * 组件测试在本项目里不做（ARCHITECTURE 1.7），所以约束只能落在这里。
 */

/**
 * 一句说得准的截断说明。
 *
 * `limitEntries` 必须是 `ScanResult.limitEntries`——本次扫描**实际生效**的
 * 上限，不许传常量、不许在调用点拼数字。
 *
 * # 为什么必须提「目录可能显示为空」
 *
 * DFS 中途 `break` 时，边界那个目录已经进了扁平表、它的孩子没进，组树后它
 * 是个空目录；而 `prune_empty_dirs` 默认 `false`，所以它会显示出来，且与
 * 真的空目录一模一样（判据 6 的夹具钉住了这个行为）。不说这一句，用户看到
 * 「我的目录是空的」会以为笔记丢了——而磁盘上明明有 12 篇。
 */
export function truncationNotice(limitEntries: number): string {
  return (
    `扫描在 ${limitEntries} 个条目处提前停止：目录也占条目，` +
    `所以能看到的笔记不超过 ${limitEntries} 篇。` +
    `被截断的位置上，目录可能显示为空——磁盘上它并不是空的。`
  )
}
